import numpy as np

"""
===========================================
工具函数模块 - 近端算子（Proximal Operators）
===========================================

【文件作用】
本文件实现了优化算法中使用的近端算子，特别是L1正则化的软阈值算子。
软阈值算子是PGD和FISTA算法处理L1正则项的核心工具，用于产生稀疏解。

【主要功能】
- soft_thresholding(): 实现软阈值算子，处理L1正则化
- 这是L1范数近端算子的解析解
- 被PGD、FISTA算法调用，用于更新解向量

【模块职责】
为近端梯度算法提供核心的近端算子实现，特别是求解 Lasso 问题所需的软阈值算子

【在优化框架中的位置】
Lasso 问题: minimize F(x) = f(x) + g(x)
- f(x) = (1/2)||Ax - b||₂² (光滑项，problem_lasso.py 处理)
- g(x) = λ||x||₁ (非光滑项，本文件处理)

近端梯度算法框架:
  xₖ₊₁ = prox_g(xₖ - α∇f(xₖ))
         ↑ 本文件实现
"""

def soft_thresholding(u, threshold):
    """
    ==========================================
    【函数名称】软阈值算子 / L1 近端算子
    ==========================================

    【数学定义】
    这个函数计算以下优化问题的解析解:

    prox_λ||·||₁(u) = argmin_x { (1/2)||x - u||₂² + λ||x||₁ }

    其中:
    - u: 输入向量（通常是梯度下降后的临时结果）
    - λ (threshold): L1 正则化参数
    - x: 待求解的输出向量

    【解析解公式】
    对每个分量 i，解为:
    xᵢ = sign(uᵢ) * max(|uᵢ| - λ, 0)

    等价的分段形式:
    xᵢ = { uᵢ - λ,    if uᵢ > λ      (正数收缩)
         { 0,         if |uᵢ| ≤ λ    (小值归零)
         { uᵢ + λ,    if uᵢ < -λ     (负数收缩)

    ==========================================
    【完整数学推导：为什么可以这样求】
    ==========================================

    【推导目标】
    求解 x* = argmin_x { (1/2)||x - u||₂² + λ||x||₁ }

    【步骤1: 问题可分解性】
    因为范数 ||x||₁ = Σᵢ|xᵢ|，目标函数可以写成:

    F(x) = Σᵢ [(1/2)(xᵢ - uᵢ)² + λ|xᵢ|]

    各分量相互独立，可以分别优化:
    xᵢ* = argmin_xᵢ { (1/2)(xᵢ - uᵢ)² + λ|xᵢ| }

    【步骤2: 处理绝对值的不可微性】
    由于 |xᵢ| 在 0 处不可微，需要分情况讨论:

    ┌─ 情况A: 假设 xᵢ* > 0 ─┐
    │ 则 |xᵢ| = xᵢ          │
    │ 问题变为:              │
    │ min_xᵢ { (1/2)(xᵢ - uᵢ)² + λxᵢ } │
    │                        │
    │ 求导并令为零:          │
    │ (xᵢ - uᵢ) + λ = 0     │
    │ ⟹ xᵢ = uᵢ - λ         │
    │                        │
    │ 这个解有效当且仅当:    │
    │ xᵢ > 0 ⟹ uᵢ - λ > 0 ⟹ uᵢ > λ │
    └────────────────────────┘

    ┌─ 情况B: 假设 xᵢ* < 0 ─┐
    │ 则 |xᵢ| = -xᵢ         │
    │ 问题变为:              │
    │ min_xᵢ { (1/2)(xᵢ - uᵢ)² - λxᵢ } │
    │                        │
    │ 求导并令为零:          │
    │ (xᵢ - uᵢ) - λ = 0     │
    │ ⟹ xᵢ = uᵢ + λ         │
    │                        │
    │ 这个解有效当且仅当:    │
    │ xᵢ < 0 ⟹ uᵢ + λ < 0 ⟹ uᵢ < -λ │
    └────────────────────────┘

    ┌─ 情况C: 假设 xᵢ* = 0 ─┐
    │ 需要用次梯度条件验证   │
    │                        │
    │ 在 xᵢ = 0 处，目标函数的次梯度为: │
    │ ∂F = -uᵢ + λ·∂|xᵢ|    │
    │                        │
    │ 其中 ∂|0| = [-1, 1] (次梯度集合) │
    │                        │
    │ 最优性条件: 0 ∈ ∂F     │
    │ ⟺ 0 ∈ {-uᵢ + λs | s ∈ [-1, 1]} │
    │ ⟺ uᵢ ∈ [-λ, λ]        │
    │ ⟺ |uᵢ| ≤ λ            │
    └────────────────────────┘

    【步骤3: 综合结果】
    综合三种情况:

    xᵢ* = { uᵢ - λ,    当 uᵢ > λ
          { 0,         当 |uᵢ| ≤ λ
          { uᵢ + λ,    当 uᵢ < -λ

    【步骤4: 向量化简写】
    上述分段函数可以优雅地表示为:

    xᵢ* = sign(uᵢ) · max(|uᵢ| - λ, 0)

    验证正确性:
    • uᵢ > λ:    sign(uᵢ)=1,  max(uᵢ-λ, 0) = uᵢ-λ ✓
    • |uᵢ| ≤ λ:  max(|uᵢ|-λ, 0) = 0 ✓
    • uᵢ < -λ:   sign(uᵢ)=-1, max(-uᵢ-λ, 0)·(-1) = uᵢ+λ ✓

    ==========================================
    【几何与直观理解】
    ==========================================

    【一维视角】
    想象数轴上的点 u:
    - 没有 L1 正则化: 最优解就是 u
    - 加入 L1 正则化: 在原点 0 处施加"磁力"
    - 如果 u 离 0 远 (|u| > λ): 磁力不够强，只能拉近 λ 距离
    - 如果 u 离 0 近 (|u| ≤ λ): 磁力足够强，直接拉到 0

    【为什么叫"软"阈值】
    对比硬阈值和软阈值:

    硬阈值: x = { u,  if |u| > λ    ← 保持原值或归零（不连续）
                { 0,  otherwise

    软阈值: x = sign(u)·max(|u|-λ, 0) ← 连续收缩（平滑过渡）

    "软"指的是平滑、连续的收缩效果

    ==========================================
    【L1 正则化的三大效果】
    ==========================================

    1️⃣ 稀疏性 (Sparsity)
       - 绝对值小于 λ 的分量被精确置零
       - 产生稀疏解向量（许多元素为 0）

    2️⃣ 特征选择 (Feature Selection)
       - 非零分量 ⟺ 重要特征
       - 零分量 ⟺ 冗余特征（自动剔除）

    3️⃣ 收缩效应 (Shrinkage)
       - 即使是非零分量，也向 0 收缩了 λ
       - 避免参数过大，防止过拟合

    这就是 Lasso 能同时做回归和特征选择的数学原理！

    ==========================================
    【代码实现细节】
    ==========================================

    L1 正则化的近端算子 (Soft Thresholding Operator)
    prox(u) = sign(u) * max(|u| - threshold, 0)

    Args:
        u (ndarray): 输入向量，形状 (n_features,)
                     通常是 u = x - α∇f(x) (梯度下降的临时结果)

        threshold (float): 阈值参数 λ
                          在近端梯度法中，threshold = λ * α
                          其中 λ 是正则化参数，α 是步长

    Returns:
        ndarray: 软阈值算子的输出，形状 (n_features,)
                每个分量独立应用了软阈值操作

    【numpy 向量化操作】
    - np.sign(u): 逐元素提取符号 {-1, 0, +1}
    - np.abs(u): 逐元素取绝对值
    - np.maximum(..., 0): 逐元素与 0 取最大值
    - *: 逐元素相乘

    【计算复杂度】O(d)，其中 d = len(u)

    ==========================================
    【数值示例】
    ==========================================

    示例1: 基本用法
    >>> u = np.array([2.5, 0.8, -1.5, -0.3])
    >>> threshold = 1.0
    >>> soft_thresholding(u, threshold)
    array([1.5, 0.0, -0.5, 0.0])

    逐元素解释:
    • u[0] = 2.5 > 1.0   → 收缩: sign(2.5) * max(2.5-1.0, 0) = 1.5
    • u[1] = 0.8, |0.8| < 1.0 → 归零: 0.0
    • u[2] = -1.5 < -1.0 → 收缩: sign(-1.5) * max(1.5-1.0, 0) = -0.5
    • u[3] = -0.3, |-0.3| < 1.0 → 归零: 0.0

    示例2: 不同阈值的影响
    >>> u = np.array([3, 2, 1, 0, -1, -2, -3])
    >>> soft_thresholding(u, 0.5)
    array([2.5, 1.5, 0.5, 0.0, -0.5, -1.5, -2.5])  # 小阈值，少归零

    >>> soft_thresholding(u, 1.5)
    array([1.5, 0.5, 0.0, 0.0, 0.0, -0.5, -1.5])   # 大阈值，多归零

    ==========================================
    【在近端梯度算法中的使用】
    ==========================================

    典型的近端梯度法（Proximal Gradient Descent）迭代:

    ```python
    for iteration in range(max_iter):
        # 步骤1: 梯度下降步（处理光滑项 f(x)）
        grad = gradient(A, b, x)  # ∇f(x) = Aᵀ(Ax - b)
        u = x - alpha * grad       # 临时更新

        # 步骤2: 近端算子步（处理非光滑项 g(x)）
        x_new = soft_thresholding(u, lambda_reg * alpha)

        # 等价于求解: argmin_x { (1/2)||x - u||² + (λα)||x||₁ }
    ```

    【为什么要这样分两步】
    - 直接优化 f(x) + g(x) 很难（g 不可微）
    - 分而治之: 光滑项用梯度，非光滑项用近端算子
    - 每步都有解析解，避免内层迭代

    ==========================================
    【与其他正则化对比】
    ==========================================

    L1 (Lasso):     prox(u) = sign(u)·max(|u|-λ, 0)  → 稀疏解
    L2 (Ridge):     prox(u) = u/(1+2λ)               → 等比收缩，不稀疏
    Elastic Net:    结合 L1 和 L2                    → 折中方案

    L1 的独特优势是能产生精确的零元素（稀疏性）！
    """
    return np.sign(u) * np.maximum(np.abs(u) - threshold, 0)