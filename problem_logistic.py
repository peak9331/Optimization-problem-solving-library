import numpy as np

"""
===========================================
逻辑回归优化问题的数学函数模块
===========================================

【文件作用】
本文件定义了Logistic回归问题的数学函数，包括对数损失函数、梯度函数和Lipschitz常数计算。
这些函数被优化算法（PGD、FISTA）调用，用于求解二分类问题。

【主要功能】
- loss(): 计算逻辑回归的对数损失函数
- gradient(): 计算损失函数的梯度
- calc_lipschitz(): 计算Lipschitz常数，用于确定最优步长

【文件总体作用】
这个文件实现的是 **逻辑回归 (Logistic Regression)** 问题

【与 Lasso 回归的重要区别】
┌────────────────────┬─────────────────┬─────────────────┐
│      特性          │ Lasso 回归      │ 逻辑回归（本文件）│
├────────────────────┼─────────────────┼─────────────────┤
│ 任务类型           │ 回归            │ 分类            │
│ 损失函数           │ L2 平方损失     │ 对数损失        │
│ 公式               │ ½∥Ax-b∥₂²      │ log(1+exp(-yᵢwᵀxᵢ))│
│ 标签范围           │ 连续值          │ {-1, +1}        │
│ 输出               │ 连续值          │ 概率 → 类别     │
│ 常见正则化         │ L1 范数         │ L2 范数         │
└────────────────────┴─────────────────┴─────────────────┘

【逻辑回归的完整优化问题】
minimize F(x) = f(x) + g(x)

其中:
f(x) = (1/m) Σᵢ log(1 + exp(-bᵢ·aᵢᵀx))  ← 对数损失（本文件实现）
g(x) = λ∥x∥₂² 或 λ∥x∥₁               ← 正则化项（通常用 L2）

注意: 本文件只实现损失函数 f(x)，正则化项需另外添加

===========================================
【关键问题：逻辑回归使用什么范数？】
===========================================

【答案】本文件的损失函数 **不直接使用范数**！

逻辑回归的损失是 **对数损失（Log Loss）**，不是范数损失

但在以下方面涉及范数:

1️⃣ Lipschitz 常数计算: 使用 **L2 范数**（矩阵谱范数）
2️⃣ 正则化项（未在本文件实现）: 通常使用 **L2 范数**

【对数损失 vs 范数损失】
• L2 损失: ½∥Ax - b∥₂² = ½Σᵢ(aᵢᵀx - bᵢ)²
  → 回归问题，假设误差服从高斯分布

• 对数损失: Σᵢ log(1 + exp(-bᵢ·aᵢᵀx))
  → 分类问题，基于最大似然估计
  → 对应伯努利分布假设

===========================================
【三个函数的详细解析】
===========================================
"""

def loss(A, b, x):
    """
    【作用】计算逻辑回归的损失函数（对数损失 / 交叉熵损失）

    【是否使用范数】❌ 不使用范数！使用对数函数

    【数学公式】
    f(x) = (1/m) Σᵢ₌₁ᵐ log(1 + exp(-bᵢ·aᵢᵀx))

    其中:
    - m: 样本数量
    - aᵢ: 第 i 个样本的特征向量（A 的第 i 行）
    - bᵢ ∈ {-1, +1}: 第 i 个样本的标签
    - x: 待优化的权重向量
    - aᵢᵀx: 线性得分（logits）

    【物理意义】
    1. z = -bᵢ·aᵢᵀx:
       - 如果预测正确（bᵢ 和 aᵢᵀx 同号），z < 0，log(1+exp(z)) ≈ 0
       - 如果预测错误（bᵢ 和 aᵢᵀx 异号），z > 0，log(1+exp(z)) 很大

    2. log(1 + exp(z)):
       - 平滑的 0-1 损失近似
       - 可微，便于优化
       - 凸函数，保证全局最优

    【为什么不用范数损失】
    范数损失（如 L2）适用于回归:
    • (aᵢᵀx - bᵢ)²: 假设标签是连续值

    对数损失适用于分类:
    • log(1 + exp(-bᵢ·aᵢᵀx)):
      - 基于概率模型（伯努利分布）
      - 最大似然估计
      - 标签是离散的 {-1, +1}

    【与交叉熵的关系】
    逻辑回归概率: P(y=1|x) = σ(wᵀx) = 1/(1+exp(-wᵀx))

    交叉熵损失: -[y·log(p) + (1-y)·log(1-p)]

    当 y ∈ {-1, +1} 时，可以写成:
    log(1 + exp(-y·wᵀx))

    这就是本函数实现的形式！

    【代码逐行解析】
    """
    m = A.shape[0]  # 样本数量

    # 计算 z = -b * (A @ x)
    # A @ x: (m,) 向量，每个元素是 aᵢᵀx（第 i 个样本的得分）
    # b * (A @ x): 逐元素相乘，得到 bᵢ·aᵢᵀx
    # -b * (A @ x): 取负，得到 -bᵢ·aᵢᵀx
    z = -b * (A @ x)

    # 计算对数损失并平均
    # np.exp(z): exp(-bᵢ·aᵢᵀx)
    # 1 + np.exp(z): 1 + exp(-bᵢ·aᵢᵀx)
    # np.log(...): log(1 + exp(-bᵢ·aᵢᵀx))
    # np.sum(...): 求和 Σᵢ
    # / m: 平均
    return np.sum(np.log(1 + np.exp(z))) / m

    """
    【数值稳定性注意】
    当 z 很大时，exp(z) 会溢出！
    
    更稳定的实现:
    log(1 + exp(z)) = max(0, z) + log(1 + exp(-|z|))
    
    但 numpy 通常能处理，这里保持简单形式
    """

def gradient(A, b, x):
    """
    【作用】计算逻辑回归损失函数的梯度

    【对什么求导】对 **对数损失** 求导，不是对范数求导！

    【数学推导】
    f(x) = (1/m) Σᵢ log(1 + exp(-bᵢ·aᵢᵀx))

    对 x 求导:
    ∂f/∂x = (1/m) Σᵢ ∂/∂x[log(1 + exp(-bᵢ·aᵢᵀx))]

    使用链式法则:
    ∂/∂x[log(1 + exp(-bᵢ·aᵢᵀx))]
    = [1/(1 + exp(-bᵢ·aᵢᵀx))] · exp(-bᵢ·aᵢᵀx) · (-bᵢ·aᵢ)
    = -bᵢ·aᵢ · [exp(-bᵢ·aᵢᵀx)/(1 + exp(-bᵢ·aᵢᵀx))]

    注意到:
    exp(-z)/(1 + exp(-z)) = 1/(1 + exp(z))

    所以:
    ∂f/∂x = -(1/m) Σᵢ bᵢ·aᵢ · [1/(1 + exp(bᵢ·aᵢᵀx))]
          = -(1/m) Σᵢ bᵢ·aᵢ·qᵢ
          = -(1/m) AᵀDq

    其中 qᵢ = 1/(1 + exp(bᵢ·aᵢᵀx))，D = diag(b)

    向量形式: ∇f(x) = -(1/m) Aᵀ(b ⊙ q)

    【梯度的物理意义】
    qᵢ = 1/(1 + exp(bᵢ·aᵢᵀx)):
    - 当前模型对样本 i 的"不确定性"
    - 如果预测很确定（正确或错误），qᵢ 接近 0
    - 如果预测不确定，qᵢ 接近 0.5

    bᵢ·qᵢ·aᵢ:
    - 错误分类样本的加权特征向量
    - 指示如何调整权重以减少损失

    【与 L2 损失梯度对比】
    L2 损失: ∇[(1/2)∥Ax - b∥₂²] = Aᵀ(Ax - b)  ← 简单线性
    对数损失: ∇[Σ log(1+exp(...))] = -Aᵀ(b⊙q)  ← 非线性，带概率权重

    【代码逐行解析】
    """
    m = A.shape[0]  # 样本数量

    # 计算 z = b * (A @ x) = bᵢ·aᵢᵀx
    z = b * (A @ x)

    # 计算 q = 1 / (1 + exp(z))
    # qᵢ = 1 / (1 + exp(bᵢ·aᵢᵀx))
    # 这是逻辑函数（sigmoid）的一个变体
    q = 1 / (1 + np.exp(z))

    # 计算梯度: -(1/m) * Aᵀ(b ⊙ q)
    # b * q: 逐元素相乘，得到 bᵢ·qᵢ
    # A.T @ (b * q): 矩阵向量乘法，得到 Aᵀ(b⊙q)
    # -(1/m) * ...: 取负并平均
    grad = -(1/m) * (A.T @ (b * q))
    return grad

    """
    【数值稳定性注意】
    当 z 很大时，exp(z) 溢出，但 1/(1+exp(z)) → 0
    
    更稳定的实现:
    if z > 0:
        q = exp(-z) / (1 + exp(-z))
    else:
        q = 1 / (1 + exp(z))
    """

def calc_lipschitz(A):
    """
    【作用】计算逻辑回归梯度的 Lipschitz 常数

    【使用的范数】矩阵的 **L2 范数**（谱范数）

    【数学公式】
    L = ∥A∥₂² / (4m)

    其中:
    - ∥A∥₂: 矩阵 A 的谱范数（最大奇异值）
    - m: 样本数量
    - 系数 1/(4m): 来自逻辑函数的二阶导数上界

    【为什么是这个形式】

    对于逻辑回归损失 f(x) = (1/m) Σᵢ log(1 + exp(-bᵢ·aᵢᵀx)):

    Hessian 矩阵（二阶导数）:
    H = ∇²f(x) = (1/m) Σᵢ qᵢ(1-qᵢ)·aᵢaᵢᵀ

    其中 qᵢ = σ(bᵢ·aᵢᵀx) ∈ (0, 1)

    关键性质: qᵢ(1-qᵢ) ≤ 1/4 （在 qᵢ = 1/2 时取最大值）

    因此:
    H ⪯ (1/m) · (1/4) · Σᵢ aᵢaᵢᵀ = (1/4m) · AᵀA

    Lipschitz 常数 L 满足:
    ∥H∥₂ ≤ L

    所以:
    L = λₘₐₓ(H) ≤ (1/4m) · λₘₐₓ(AᵀA) = (1/4m) · ∥A∥₂²

    【与 Lasso 的 Lipschitz 常数对比】
    Lasso (L2 损失): L = ∥A∥₂²
    Logistic: L = ∥A∥₂² / (4m)

    逻辑回归的 L 更小 → 可以用更大的步长 → 收敛可能更快

    【为什么需要 Lipschitz 常数】
    1. 确定步长上界: α ≤ 1/L 保证收敛
    2. 最优步长: α = 1/L
    3. 理论保证: 收敛速率 O(L/k)

    【代码解析】
    """
    m = A.shape[0]  # 样本数量

    # 计算 L = ∥A∥₂² / (4m)
    # np.linalg.norm(A, ord=2): 计算 L2 范数（谱范数）
    # **2: 平方
    # / (4 * m): 除以 4m
    return (np.linalg.norm(A, ord=2)**2) / (4 * m)
    #      ↑_____________↑ ord=2 指定 L2 范数（谱范数）

    """
    【范数类型说明】
    这里使用矩阵的 L2 范数（谱范数），不是 L1 范数
    
    如果用 L1 范数:
    L_L1 = (∥A∥₁²) / (4m)  ← 会更保守（L 更大，步长更小）
    
    L2 范数通常给出更紧的界，是标准选择
    """

"""
===========================================
【总结：逻辑回归使用的范数】
===========================================

1️⃣ 损失函数 loss():
   ❌ 不使用范数！使用 **对数函数**
   - f(x) = Σ log(1 + exp(-bᵢ·aᵢᵀx))
   - 基于最大似然估计，不是范数损失

2️⃣ 梯度计算 gradient():
   ❌ 不对范数求导！对 **对数损失** 求导
   - ∇f(x) = -(1/m)Aᵀ(b⊙q)
   - 涉及 sigmoid 函数，不是简单的线性梯度

3️⃣ Lipschitz 常数 calc_lipschitz():
   ✅ 使用矩阵的 **L2 范数**（谱范数）
   - L = ∥A∥₂² / (4m)
   - 目的: 确定最优步长

4️⃣ 正则化项（未在本文件实现）:
   通常使用 **L2 范数**: λ∥x∥₂²
   - 与 Lasso 不同（Lasso 用 L1）
   - L2 正则化逻辑回归不产生稀疏性
   - 如果需要稀疏性，可以加 L1 正则化（L1-regularized Logistic Regression）

===========================================
【核心区别总结】
===========================================

┌─────────────┬──────────────────┬──────────────────┐
│   项目      │ Lasso 回归       │ 逻辑回归（本文件）│
├─────────────┼──────────────────┼──────────────────┤
│ 损失函数    │ L2 范数平方      │ 对数损失（非范数）│
│ 公式        │ ½∥Ax-b∥₂²       │ Σlog(1+exp(...)) │
│ 梯度        │ Aᵀ(Ax-b)         │ -Aᵀ(b⊙q)         │
│ Lipschitz   │ ∥A∥₂²           │ ∥A∥₂²/(4m)       │
│ 正则化      │ L1 范数          │ L2 范数          │
│ 任务        │ 回归            │ 分类            │
│ 标签        │ 连续值          │ {-1, +1}        │
│ 稀疏性      │ 是（L1）        │ 否（L2）        │
└─────────────┴──────────────────┴──────────────────┘

===========================================
【重要结论】
===========================================

逻辑回归的损失函数 **不是基于范数的**！

- ❌ 不是 L1 损失: ∥Ax - b∥₁
- ❌ 不是 L2 损失: ∥Ax - b∥₂²
- ✅ 是对数损失: Σ log(1 + exp(-y·wᵀx))

这是基于概率模型（最大似然估计）的损失函数，
专门设计用于分类问题。

只有在以下地方涉及范数:
1. Lipschitz 常数计算（矩阵 L2 范数）
2. 正则化项（通常 L2 范数，可选 L1）
"""
